#!/usr/bin/env Rscript
# Capture genuine printed output with knitr. Normal builds read the saved files;
# authors regenerate explicitly and CI regenerates on every build.
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 1L) stop("Usage: Rscript docs/render_r_examples.R /path/to/PDMPSamplersR")
script <- sub("^--file=", "", grep("^--file=", commandArgs(), value = TRUE))
docs <- dirname(normalizePath(script))
r_source <- normalizePath(args[[1L]], mustWork = TRUE)
Sys.setenv(RENV_PROJECT = docs, RENV_PROFILE = "examples",
           RENV_PATHS_LIBRARY = file.path(docs, "renv", "library"),
           RENV_CONFIG_AUTO_SNAPSHOT = "FALSE")
source(file.path(docs, "renv", "activate.R"))
renv::restore(prompt = FALSE)

# The checkout supplies the R interface; its runtime dependencies are locked in
# the examples profile. Reinstall each time so CI tests the checked-out code.
library <- .libPaths()[[1L]]
status <- system2(file.path(R.home("bin"), "R"), c(
  "CMD", "INSTALL", shQuote(paste0("--library=", library)), shQuote(r_source)
))
if (status != 0L) stop("Failed to install the local R interface")
options(digits = 5, pdmpsamplersr_config_julia_project_dir = docs)
julia_home <- Sys.getenv("PDMPSAMPLERS_DOCS_JULIA_BINDIR")
if (nzchar(julia_home)) options(JULIA_HOME = julia_home)

page <- readLines(file.path(docs, "src", "getting-started.md"), warn = FALSE)
output_dir <- file.path(docs, "examples", "output")
dir.create(output_dir, recursive = TRUE, showWarnings = FALSE)
outputs <- list()
for (label in c("manual", "Stan", "brms")) {
  heading <- which(page == paste0("== R - ", label))
  if (length(heading) != 1L) stop("Expected one R tab: ", label)
  start <- heading + 2L
  if (page[[start]] != "```r") stop("Expected R code after tab: ", label)
  end <- start + which(page[(start + 1L):length(page)] == "```")[[1L]]
  code <- paste(page[(start + 1L):(end - 1L)], collapse = "\n")
  expressions <- parse(text = code)
  if (length(expressions) < 3L) stop("Missing R setup or summaries: ", label)
  # These examples finish with the two summary expressions shown to readers.
  as_code <- function(x) paste(vapply(x, function(e) paste(deparse(e), collapse = "\n"), ""), collapse = "\n")
  setup <- as_code(head(expressions, -2L))
  summaries <- as_code(tail(expressions, 2L))
  env <- new.env(parent = globalenv())
  text <- paste0(
    "```{r setup, include=FALSE, error=FALSE}\n", setup, "\n```\n\n",
    "```{r summaries, echo=FALSE, error=FALSE, warning=FALSE, message=FALSE}\n",
    summaries, "\n```\n"
  )
  cat("Running R ", label, " example\n", sep = "")
  rendered <- knitr::knit(text = text, envir = env, quiet = TRUE)
  if (label == "brms") {
    estimate <- brms::fixef(env$fit)[, "Estimate"]
    covariance <- stats::vcov(env$fit)
  } else {
    estimate <- mean(env$result)
    covariance <- PDMPSamplersR::cov(env$result)
  }
  stopifnot(max(abs(estimate - c(1, -1))) < 0.1,
            max(abs(covariance - matrix(c(1, .5, .5, 2), 2, 2))) < 0.15)
  header <- paste0("<!-- Generated by docs/update-examples.sh; source-sha256: ",
                   digest::digest(code, algo = "sha256", serialize = FALSE), " -->\n\n")
  path <- file.path(output_dir, paste0("getting-started-r-", tolower(label), ".md"))
  outputs[[path]] <- paste0(header, rendered)
}
# Publish a complete set only after all examples have executed and passed.
for (path in names(outputs)) writeLines(outputs[[path]], path)
